def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mjcf", required=True)
    parser.add_argument("--csv", nargs="+", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--gravity", type=float, default=-9.81)
    parser.add_argument("--cutoff-hz", type=float, default=25.0)
    parser.add_argument("--edge-trim-s", type=float, default=0.10)
    parser.add_argument("--min-speed", type=float, default=0.015)
    parser.add_argument("--cruise-max-accel", type=float, default=0.5)
    parser.add_argument(
        "--train-sine-hz", type=float, nargs="+", default=[0.5],
        help="inertia-sine frequencies used for fitting (default: 0.5)",
    )
    parser.add_argument(
        "--held-sine-hz", type=float, nargs="+", default=[1.0],
        help="inertia-sine frequencies reserved for validation (default: 1.0)",
    )
    args = parser.parse_args()

    paths = [Path(item) for pattern in args.csv for item in sorted(glob.glob(pattern))]
    if not paths:
        raise SystemExit("no CSV files matched")
    logs = [log for log in (load_log(path) for path in paths) if log is not None]
    if len(logs) != len(JOINT_NAMES):
        raise SystemExit(f"expected 14 usable active-joint logs, found {len(logs)}")
    if sorted(log.active_joint for log in logs) != list(range(len(JOINT_NAMES))):
        raise SystemExit("logs must contain exactly one active trial for every joint")

    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    engine = MujocoEngine(args.mjcf, zero_passive=True, gravity=args.gravity)
    trials: list[TrialData] = []
    print(f"loaded {len(logs)} logs; gravity={args.gravity:+.2f}; passive terms zeroed for rigid-body residual")
    for log in logs:
        qdd, qd_filtered = filtered_qdd(log.qd, log.fs, args.cutoff_hz)
        torque = engine.rbd_torque(log.q, qd_filtered, qdd)
        joint = log.active_joint
        train, held = _phase_masks(
            log.phase, qd_filtered[:, joint], qdd[:, joint], log.fs,
            args.edge_trim_s, args.min_speed, args.cruise_max_accel,
            args.train_sine_hz, args.held_sine_hz,
        )
        if int(train.sum()) < 100 or int(held.sum()) < 100:
            raise SystemExit(f"{log.path.name}: insufficient train/held samples ({train.sum()}/{held.sum()})")
        trials.append(TrialData(
            joint=joint, path=log.path, phase=log.phase,
            qdd=qdd[:, joint], qd=qd_filtered[:, joint],
            residual=log.tau[:, joint] - torque[:, joint], train=train, held_out=held,
        ))
        print(f"  {JOINT_NAMES[joint]}: train={int(train.sum())}, held={int(held.sum())}")

    rows: list[dict] = []
    for trial in sorted(trials, key=lambda item: item.joint):
        theta, train_rmse, held_rbd, held_default, held_fit, held_mappable, condition = _fit_trial(trial)
        row = {
            "joint": JOINT_NAMES[trial.joint],
            "source_csv": trial.path.name,
            "train_samples": int(trial.train.sum()),
            "held_out_samples": int(trial.held_out.sum()),
            "armature_kg_m2": float(theta[0]),
            "frictionloss_nm": float(theta[1]),
            "damping_nm_s_rad": float(theta[2]),
            "bias_nm": float(theta[3]),
            "design_condition": condition,
            "train_rmse_nm": train_rmse,
            "held_rbd_rmse_nm": held_rbd,
            "held_default_rmse_nm": held_default,
            "held_fitted_rmse_nm": held_fit,
            "held_mappable_no_bias_rmse_nm": held_mappable,
        }
        rows.append(row)
        print(
            f"{row['joint']:<22} A={row['armature_kg_m2']:.5f} "
            f"Fc={row['frictionloss_nm']:.4f} B={row['damping_nm_s_rad']:.4f} "
            f"bias={row['bias_nm']:+.4f} held: {held_rbd:.4f} -> {held_fit:.4f} Nm"
        )

    _write_csv(output / "passive_parameter_fit.csv", rows)
    _plot_validation(rows, output / "heldout_residual_rmse.png")
    _plot_parameters(rows, output / "passive_parameter_estimates.png")
    _write_reports(output, rows, args, paths)
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
