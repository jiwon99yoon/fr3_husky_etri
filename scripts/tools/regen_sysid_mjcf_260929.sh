#!/usr/bin/env bash
# Regenerate the MuJoCo model used by the 2026-09-29 SysID analysis (data/sysid_*_260929).
#
# The reports and manifests there reference /tmp/dual_fr3_plate_260929.xml, which does not survive a
# reboot. This rebuilds it from fr3_husky_description/mjcf/dual_fr3.xml.xacro with the same xacro
# arguments. Verified on 2026-11-03: the static-gravity and passive-fit CSVs came out byte-identical
# with the rebuilt file (see data/sysid_260929_README.md).
#
# Needs franka_description and fr3_husky_description on the ROS package path:
#   source /opt/ros/jazzy/setup.bash
#   source ~/fr3_ws/install/setup.bash        # franka_description (mjcf/)
#   source ~/etri_ws/install/setup.bash       # fr3_husky_description
#   scripts/tools/regen_sysid_mjcf_260929.sh [output.xml]   # default /tmp/dual_fr3_plate_260929.xml
#
# husky_description is NOT needed: its mjcf/ is missing on some PCs, and with mobile:=false the Husky
# macros emit nothing, so the two Husky includes are replaced by a stub with empty macros.
set -euo pipefail

out="${1:-/tmp/dual_fr3_plate_260929.xml}"
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="$repo/fr3_husky_description/mjcf/dual_fr3.xml.xacro"
# sha256 of the model verified on 2026-11-03, hashed without xacro's "autogenerated ... from <path>"
# comment line. The file still embeds absolute mesh paths of franka_description
# (/home/dyros/fr3_ws/install/...), so another install prefix gives another hash for the same model.
verified_sha256="deab1afdb06ac933393cc5e5358bfcba1f6291e1405f9b4bbe9f12f3bccfa18d"

command -v xacro >/dev/null || { echo "xacro not found: source /opt/ros/jazzy/setup.bash" >&2; exit 1; }
[[ -f "$src" ]] || { echo "missing $src" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
cat > "$tmp/husky_stub.xml.xacro" <<'EOF'
<?xml version="1.0"?>
<mujoco xmlns:xacro="http://www.ros.org/wiki/xacro">
  <xacro:macro name="husky_assets"/>
  <xacro:macro name="husky" params="prefix as_two_wheels **body"/>
</mujoco>
EOF

# Same edit as the verified regeneration: drop husky_macro.xml.xacro, point assets.xml.xacro at the stub.
sed -e '\#\$(find husky_description)/mjcf/husky_macro\.xml\.xacro#d' \
    -e "s#\$(find husky_description)/mjcf/assets\.xml\.xacro#$tmp/husky_stub.xml.xacro#" \
    "$src" > "$tmp/dual_fr3.xml.xacro"
if grep -qF '$(find husky_description)' "$tmp/dual_fr3.xml.xacro"; then
    echo "dual_fr3.xml.xacro changed: Husky includes not replaced" >&2
    exit 1
fi

xacro "$tmp/dual_fr3.xml.xacro" hand:=false with_realsense:=false with_azure:=false mobile:=false \
    > "$tmp/out.xml" 2> "$tmp/xacro.log" || { cat "$tmp/xacro.log" >&2; exit 1; }
mkdir -p "$(dirname "$out")"
mv "$tmp/out.xml" "$out"

sha="$(grep -v 'autogenerated by xacro from' "$out" | sha256sum | cut -d' ' -f1)"
echo "wrote $out"
if [[ "$sha" == "$verified_sha256" ]]; then
    echo "sha256 matches the 2026-11-03 verified model"
else
    echo "sha256 $sha differs from the verified $verified_sha256"
    echo "  expected if franka_description is installed elsewhere (mesh paths are absolute);"
    echo "  otherwise check git log of fr3_husky_description/mjcf (plate_ee.xml.xacro) since 02d7201."
fi
